(function (root) {
  'use strict';

  const number = value => Number.isFinite(value) ? value : 0;
  const signed = (value, digits = 1) => `${value < 0 ? '−' : '+'}${Math.abs(value).toFixed(digits)}`;
  const pct = (proposal, baseline) => baseline ? (proposal - baseline) / baseline * 100 : 0;
  const money = value => `${value < 0 ? '−' : '+'}$${Math.abs(Math.round(value)).toLocaleString('en-CA')}`;

  function rows(trace, run, group) {
    const metrics = trace.runs[run].metrics;
    return group ? metrics.by_group[group] : metrics.by_tick;
  }

  function series(trace, run, key, group) {
    return rows(trace, run, group).map(row => number(row[key]));
  }

  function policyAverage(values, startTick) {
    const selected = values.slice(startTick - 1);
    return selected.reduce((sum, value) => sum + value, 0) / Math.max(1, selected.length);
  }

  function metric(trace, key, group) {
    const baseline = series(trace, 'baseline', key, group);
    const policy = series(trace, 'intervention', key, group);
    const start = trace.scenario.intervention[0].starts_tick;
    return { baseline, policy, before: policyAverage(baseline, start), after: policyAverage(policy, start) };
  }

  function isFareTrace(trace) {
    return Boolean(trace && trace.study_id === 'ttc-fare-050' && trace.runs?.baseline?.metrics?.by_tick &&
      trace.runs?.intervention?.metrics?.by_tick && trace.scenario?.intervention?.[0]?.starts_tick);
  }

  function toFareScenario(trace, template) {
    if (!isFareTrace(trace)) throw new TypeError('Expected the TTC fare replay trace');
    const bus = metric(trace, 'bus_trips');
    const missed = metric(trace, 'skipped_trips');
    const shop = metric(trace, 'shop_sales');
    const burden = metric(trace, 'fare_burden_pct', 'near_poor');
    const nearBus = metric(trace, 'bus_per_week', 'near_poor');
    const revenue = metric(trace, 'fare_revenue');
    const delta = (m, label) => `${signed(pct(m.after, m.before))}% ${label}`;
    const post = `weeks ${trace.scenario.intervention[0].starts_tick}–${trace.scenario.horizon_ticks}`;
    const sectors = {
      mobility: { ...template.sectors.mobility, delta: delta(bus, 'BUS TRIPS'), chartTitle: 'SAMPLE BUS TRIPS / WEEK', unit: 'scaled synthetic trips per week', baseline: bus.baseline, policy: bus.policy,
        evidence: 'Trips are generated by the seeded rule engine. Fare response comes from transferred literature and explicit assumptions; no Toronto elasticity was measured.' },
      access: { ...template.sectors.access, title: 'Some trips do not happen.', description: 'The trace records a skipped trip when a synthetic person decides not to travel. A lost bus ride can also become a walk or drive.',
        delta: delta(missed, 'SKIPPED TRIPS'), chartTitle: 'SAMPLE SKIPPED TRIPS / WEEK', unit: 'scaled synthetic skipped trips per week', baseline: missed.baseline, policy: missed.policy,
        evidence: 'The skipped-trip count comes from the same persona decisions as the city replay. It is not an observed access loss.' },
      commerce: { ...template.sectors.commerce, title: 'Route choices reach local shops.', description: 'Completed simulated errands and assumed basket sizes determine sales at the grocery and café. Store closure is not modelled.',
        delta: delta(shop, 'SHOP SALES'), chartTitle: 'SAMPLE LOCAL SHOP SALES / WEEK', unit: 'synthetic CAD per week, scaled sample', baseline: shop.baseline, policy: shop.policy,
        evidence: 'Shop spending, plaza choice and opening-hour thresholds are assumptions. The trace does not estimate Toronto retail sales.' },
      households: { ...template.sectors.households, title: 'Near-cutoff riders carry a different burden.', description: 'This chart tracks the simulated fare burden for riders just above the Fair Pass cutoff. It does not combine census income and commuting into observed people.',
        delta: `${signed(burden.after - burden.before, 2)} PP BURDEN`, chartTitle: 'NEAR-CUTOFF FARE BURDEN / WEEK', unit: 'percent of synthetic weekly income', baseline: burden.baseline, policy: burden.policy,
        evidence: 'The Fair Pass price is observed; personas, incomes and trip choices are synthetic. This is a subgroup model output.' },
      public: { ...template.sectors.public, title: 'A higher fare meets fewer rides.', description: 'Sample fare receipts add up paid rides in the simulated district. This is neither TTC-wide revenue nor a City budget projection.',
        delta: `${money(revenue.after - revenue.before)} / WEEK`, chartTitle: 'SAMPLE FARE RECEIPTS / WEEK', unit: 'synthetic CAD per week, scaled sample', baseline: revenue.baseline, policy: revenue.policy,
        evidence: 'Receipts follow recorded simulated fares and trips. The scale factor is an assumption, and operating costs are not estimated.' },
    };
    return {
      ...template,
      trace,
      title: trace.scenario.question,
      summary: `${trace.personas.length} synthetic people make choices across two seeded worlds. ${trace.diverged_events} choices differ after the fare change; inspect them below.`,
      breadcrumb: 'BLOOR MAP · SYNTHETIC FARE TRACE', viewport: 'BATHURST–SPADINA SECTION', mapTag: 'TTC FARE / SCHEMATIC TRACE',
      location: trace.scenario.geography,
      headline: { label: `SAMPLE FARE RECEIPTS · ${post.toUpperCase()}`, value: `${money(revenue.after - revenue.before)}/wk`, direction: 'simulated difference from baseline' },
      mini: [
        { label: 'Bus trips', value: `${signed(pct(bus.after, bus.before))}%`, tone: bus.after < bus.before ? 'negative' : 'positive' },
        { label: 'Near-cutoff bus trips', value: `${signed(pct(nearBus.after, nearBus.before))}%`, tone: nearBus.after < nearBus.before ? 'negative' : 'positive' },
        { label: 'Local shop sales', value: `${signed(pct(shop.after, shop.before))}%`, tone: shop.after < shop.before ? 'negative' : 'positive' },
      ],
      narrative: 'One seeded trace drives the inspector and these charts. The fare is observed, while persona responses and local shop rules are assumptions, not a Toronto forecast.',
      sourceRibbon: `Seed ${trace.seed} · run v${trace.version} · ${trace.evidence_tier.replaceAll('_', ' ')} · ${trace.diverged_events} changed choices`,
      sectors,
    };
  }

  const api = { isFareTrace, toFareScenario, metric };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.CounterfactualTraceAdapter = api;
})(typeof window !== 'undefined' ? window : globalThis);
